const EMOJI_STRIP_RE = /[\u{1F300}-\u{1FAFF}\u2600-\u27BF\uFE0F]/gu

export function stripEmoji(text: string | null | undefined): string {
  return String(text || '')
    .replace(EMOJI_STRIP_RE, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
}
